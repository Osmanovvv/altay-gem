GREEN = "1F4A30"
HEAD_BG = "F5F1E8"
WARN_BG = "FDF0D5"
STOP_BG = "F7DEDE"


def num(v):
    try:
        return float(str(v).replace(",", "."))
    except Exception:
        return 0.0


def main():
    src = openpyxl.load_workbook(SRC, read_only=True)
    ws = src.active
    rows = list(ws.iter_rows(values_only=True))
    hdr = [str(h).strip() if h else "" for h in rows[0]]
    idx = {h: i for i, h in enumerate(hdr)}

    def col(r, n):
        i = idx.get(n)
        return r[i] if i is not None and i < len(r) else None

    groups = defaultdict(list)
    for r in rows[1:]:
        if num(col(r, "Остаток")) <= 0:
            continue
        groups[str(col(r, "Группа") or "без группы").strip()].append(
            str(col(r, "Наименование") or "").strip()
        )

    out = openpyxl.Workbook()

    # --- Лист 1: раскладка групп ---
    s = out.active
    s.title = "Раскладка групп"
    headers = ["Группа из выгрузки", "Позиций", "Что это (примеры товаров)",
               "Категория на сайте", "Скоропорт", "Выкладывать", "Комментарий"]
    s.append(headers)
    for c in range(1, len(headers) + 1):
        cell = s.cell(row=1, column=c)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=GREEN)
        cell.alignment = Alignment(vertical="center", wrap_text=True)

    for name in sorted(groups, key=lambda k: -len(groups[k])):
        cat, perish, publish, note = MAP.get(name, ("?", "?", "УТОЧНИТЬ", "группы нет в раскладке"))
        samples = "; ".join(groups[name][:3])[:160]
        s.append([name, len(groups[name]), samples, cat, perish, publish, note])
        row = s.max_row
        if publish == "НЕТ":
            fill = PatternFill("solid", fgColor=STOP_BG)
        elif publish == "УТОЧНИТЬ" or cat == "СМЕШАННАЯ":
            fill = PatternFill("solid", fgColor=WARN_BG)
        else:
            fill = None
        for c in range(1, len(headers) + 1):
            cell = s.cell(row=row, column=c)
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            if fill:
                cell.fill = fill

    for c, w in zip("ABCDEFG", [26, 9, 58, 22, 12, 14, 42]):
        s.column_dimensions[c].width = w
    s.freeze_panes = "A2"

    # --- Лист 2: предлагаемые категории ---
    s2 = out.create_sheet("Категории витрины")
    s2.append(["Категория", "Что внутри", "Примерно позиций"])
    for c in range(1, 4):
        cell = s2.cell(row=1, column=c)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=GREEN)

    counts = defaultdict(int)
    for name, items in groups.items():
        cat = MAP.get(name, ("?",))[0]
        counts[cat] += len(items)
    for cat, what in CATEGORIES:
        s2.append([cat, what, counts.get(cat, 0)])
    s2.append(["СМЕШАННЫЕ группы", "разложить по названиям товаров", counts.get("СМЕШАННАЯ", 0)])
    s2.append(["не выкладывать", "пакеты, сертификаты", counts.get("—", 0)])
    for c, w in zip("ABC", [26, 52, 20]):
        s2.column_dimensions[c].width = w

