/**
 * Время СНЯТИЯ выгрузки из товароучётки — из содержимого самого файла.
 *
 * Зачем. Сверка авторитетна по каждому товару, у которого нет более свежего
 * движения (см. stock_asof), и время файла решает, что он вправе перезаписать.
 * Раньше временем считался mtime, то есть момент появления файла на сервере.
 * Живой случай 05.08.2026: товароучётка сформировала выгрузку в 09:00:36, а
 * до нас она добралась в 15:31 — по mtime файл выглядел бы новее всех продаж
 * дня и откатил бы их.
 *
 * Откуда берём. xlsx — это zip, и в локальном заголовке каждой записи лежит
 * момент её создания (DOS-время, шаг 2 секунды, БЕЗ указания зоны). У этой
 * товароучётки метка в UTC — проверено дважды и независимо: (1) по 51 продаже
 * 05.08 файл учитывал всё до 08:47:04 и не знал ничего с 09:24:43, а метка
 * 09:00:36 попала ровно в окно; (2) июльские выгрузки, скачанные сразу после
 * формирования, дают метку, совпадающую с mtime до секунды.
 *
 * ОСТАТОЧНЫЙ РИСК, принят осознанно. DOS-время по соглашению локальное. Если
 * товароучётка сменит зону сервера на восточную (например MSK), метка станет
 * «позже правды» на величину сдвига, и такой файл перезапишет продажи,
 * случившиеся в это окно. Проверка «позже появления файла у нас» ловит сдвиг
 * только больше времени доставки, поэтому полностью закрыть это содержимым
 * файла нельзя: колонка «Обновлен» даёт лишь НИЖНЮЮ границу (у живых файлов
 * отстаёт от метки на 3–7 часов). Ущерб ограничен: пострадают только товары,
 * проданные в окне сдвига, и каждый из них починится при следующей продаже
 * (чек несёт авторитетный остаток). Диагностика: время снимка и его источник
 * пишутся в лог ДО применения файла.
 */

const ZIP_LOCAL_HEADER = 0x04034b50;
/** Перекос часов, который прощаем: метка чуть «позже» файла — не сбой зоны. */
const CLOCK_SKEW_MS = 60_000;
/** Методы сжатия zip, которые реально встречаются в xlsx: без сжатия и deflate. */
const ZIP_METHODS = new Set([0, 8]);

/**
 * Самая ранняя осмысленная метка времени из локальных заголовков zip —
 * момент, когда файл начали формировать. null, если это не zip или меток нет.
 *
 * Сигнатура может случайно встретиться и внутри сжатых данных, поэтому кроме
 * неё проверяем правдоподобие соседних полей (версия и метод сжатия): это
 * снижает и без того малую вероятность ложной метки ещё на два порядка.
 */
export function readSnapshotTime(buf: Buffer): number | null {
  let earliest: number | null = null;
  // Заголовок занимает 30 байт; дальше искать сигнатуру бессмысленно.
  for (let i = 0; i + 30 <= buf.length; i++) {
    if (buf.readUInt32LE(i) !== ZIP_LOCAL_HEADER) continue;
    const versionNeeded = buf.readUInt16LE(i + 4);
    const method = buf.readUInt16LE(i + 8);
    if (versionNeeded > 63 || !ZIP_METHODS.has(method)) continue;
    const time = buf.readUInt16LE(i + 10);
    const date = buf.readUInt16LE(i + 12);
    const year = 1980 + ((date >> 9) & 0x7f);
    const month = (date >> 5) & 0x0f;
    const day = date & 0x1f;
    const hour = (time >> 11) & 0x1f;
    const minute = (time >> 5) & 0x3f;
    const second = (time & 0x1f) * 2;
    // Нулевая дата и «эпоха DOS» — заглушки архиватора, не время файла.
    if (year < 2000 || year > 2100) continue;
    if (month < 1 || month > 12 || day < 1 || day > 31) continue;
    if (hour > 23 || minute > 59 || second > 59) continue;
    const ms = Date.UTC(year, month - 1, day, hour, minute, second);
    if (earliest === null || ms < earliest) earliest = ms;
  }
  return earliest;
}

/**
 * Самое позднее «Обновлен» из строк выгрузки — НИЖНЯЯ граница момента снятия:
 * снимок не может быть раньше последнего изменения, которое в него попало.
 * Колонка подписана зоной явно («Обновлен (МСК, +3)»), поэтому не зависит от
 * настроек сервера и ловит метку, прочитанную СЛИШКОМ РАНО. null — колонки
 * нет или значения не разобрались.
 */
export function readMaxUpdatedAt(
  rows: Array<Record<string, unknown>>,
): number | null {
  if (!rows.length) return null;
  const key = Object.keys(rows[0]).find((k) => k.startsWith('Обновлен'));
  if (!key) return null;
  // Зона берётся из подписи колонки: «(МСК, +3)» → +03:00.
  const off = /\+\s*(\d{1,2})/.exec(key);
  const tz = off ? `+${String(Number(off[1])).padStart(2, '0')}:00` : 'Z';
  let max: number | null = null;
  for (const r of rows) {
    const v = r[key];
    if (typeof v !== 'string' || v.length < 10) continue;
    const ms = Date.parse(`${v.trim().replace(' ', 'T')}${tz}`);
    if (!Number.isFinite(ms)) continue;
    if (max === null || ms > max) max = ms;
  }
  return max;
}

/** Каким временем считать снимок и почему. */
export type ExportAt =
  | { atMs: number; source: 'snapshot' }
  /**
   * Метки в zip нет — берём НИЖНЮЮ границу из данных. Заведомо раньше правды,
   * то есть файл получит меньше власти, чем заслуживает: часть исправлений не
   * применится, зато откатить продажи такой файл не может.
   */
  | { atMs: number; source: 'data'; warn: string }
  | { atMs: null; source: 'rejected'; reason: string };

/**
 * Метке доверяем, если она физически возможна:
 *  - не в будущем и не позже появления файла у нас (файл не может быть
 *    сформирован после того, как записан) — иначе зона/часы сбиты;
 *  - не раньше последнего «Обновлен» в самих данных — иначе метка прочитана
 *    в зоне западнее реальной.
 * Нарушение → файл не применяем вовсе: лучше пропуск с алертом, чем тихая
 * порча остатков.
 *
 * ВРЕМЯ ФАЙЛА НА СЕРВЕРЕ КАК ЗАПАСНОЙ ВАРИАНТ НЕ ИСПОЛЬЗУЕТСЯ. Оно всегда
 * ПОЗЖЕ правды на время доставки, а «позже правды» — единственное направление,
 * которое откатывает продажи. Случай не теоретический: файл, открытый и
 * сохранённый в Excel (это делает человек, который присылает нам выгрузки —
 * проверено на goods_export_...20260702 в корне проекта), теряет ВСЕ метки zip
 * разом, они становятся 1980-01-01. Раньше такой файл молча применялся по
 * времени загрузки и откатывал день торговли. Вместо этого берём нижнюю
 * границу из данных: она заведомо раньше правды и безопасна.
 */
export function resolveExportAt(input: {
  snapshotMs: number | null;
  mtimeMs: number;
  nowMs: number;
  /** Нижняя граница из данных файла (readMaxUpdatedAt), если известна. */
  minPlausibleMs?: number | null;
}): ExportAt {
  const { snapshotMs, mtimeMs, nowMs, minPlausibleMs } = input;
  if (snapshotMs === null) {
    if (minPlausibleMs == null) {
      return {
        atMs: null,
        source: 'rejected',
        reason:
          'в файле нет ни метки времени формирования, ни колонки «Обновлен» — ' +
          'определить момент снятия выгрузки нечем. Применять нельзя: если ' +
          'между выгрузкой и доставкой прошли часы, сверка откатила бы продажи ' +
          'этого промежутка. Скачайте выгрузку заново и не открывайте её в Excel',
      };
    }
    return {
      atMs: minPlausibleMs,
      source: 'data',
      warn:
        'в файле нет метки времени формирования (обычно так бывает, если его ' +
        'открывали и сохраняли в Excel). Момент снятия взят по последнему ' +
        'изменению товара внутри файла — это заведомо раньше правды, поэтому ' +
        'часть расхождений останется до следующей выгрузки. Чтобы применялось ' +
        'полностью, присылайте файл как скачан, не открывая его.',
    };
  }
  if (snapshotMs > nowMs + CLOCK_SKEW_MS) {
    return {
      atMs: null,
      source: 'rejected',
      reason: `время формирования файла (${new Date(snapshotMs).toISOString()}) в будущем — часовой пояс сбит у товароучётки либо файл пересохранён программой на машине с другой зоной (Excel, архиватор, Проводник)`,
    };
  }
  if (snapshotMs > mtimeMs + CLOCK_SKEW_MS) {
    return {
      atMs: null,
      source: 'rejected',
      reason: `время формирования файла (${new Date(snapshotMs).toISOString()}) позже его появления на сервере (${new Date(mtimeMs).toISOString()}) — часовой пояс сбит у товароучётки либо файл пересохранён программой на машине с другой зоной`,
    };
  }
  if (minPlausibleMs != null && snapshotMs < minPlausibleMs) {
    return {
      atMs: null,
      source: 'rejected',
      reason: `время формирования файла (${new Date(snapshotMs).toISOString()}) раньше последнего изменения товара внутри него (${new Date(minPlausibleMs).toISOString()}) — метка прочитана в неверном часовом поясе`,
    };
  }
  return { atMs: snapshotMs, source: 'snapshot' };
}
