/**
 * Оценка здоровья интеграции с Эвотором (этап 2, ТЗ р.10.3 п.9).
 *
 * Чистая функция: по снимку состояния (последняя успешная сверка, число
 * зависших событий) решает, какие алерты слать исполнителю. Сам сбор снимка
 * и отправка — в ReconcileService (там БД и Telegram).
 */

/** Снимок состояния интеграции для оценки. */
export interface HealthSnapshot {
  /** Настроена ли ночная сверка (есть каталог выгрузок). */
  reconcileEnabled: boolean;
  /** Время последнего ЗАПУСКА ночной сверки (ok или error; null — ни одного). */
  lastReconcileAt: Date | null;
  /**
   * Время последнего УСПЕШНО ПРИМЕНЁННОГО снимка остатков (файл выгрузки или
   * чтение из облака). Отличается от lastReconcileAt: сверка могла запуститься
   * и осознанно пропустить протухшую выгрузку — это исправная работа защиты,
   * а не сбой. null — ни одного применения.
   */
  lastSnapshotAt?: Date | null;
  /** Кол-во событий Эвотора, зависших в 'failed' дольше порога. */
  failedEventCount: number;
  /** Включён ли страховочный поллинг документов (EVOTOR_POLL_MINUTES>0). */
  pollEnabled?: boolean;
  /** Статус последнего активного прогона поллинга (null — ещё не прогонялся). */
  pollLastStatus?: 'ok' | 'error' | null;
  /** Сколько unparsed-событий ПОЯВИЛОСЬ за последние сутки (не всего). */
  unparsedRecentCount?: number;
}

/**
 * Порог unparsed-событий за сутки. 1–2 — легитимный шум (пинг проверки URL
 * при перенастройке вебхука в кабинете); настоящая смена формата даёт десятки
 * в день (каждый чек). Порог 3 отделяет одно от другого.
 */
const UNPARSED_ALERT_MIN = 3;

export interface HealthThresholds {
  /** Сверка не ЗАПУСКАЛАСЬ дольше стольких часов — авария планировщика. */
  reconcileMaxAgeHours: number;
  /**
   * Снимок остатков не ПРИМЕНЯЛСЯ дольше стольких часов — операционный сигнал
   * «пора обновить выгрузку». Порог задаётся ритмом обновления: при недельном
   * ритме суточный порог кричал бы каждый день впустую. Не задан — сигнал
   * выключен (прежнее поведение).
   */
  snapshotMaxAgeHours?: number;
}

/** Готовый к отправке алерт. key — стабильный идентификатор проблемы. */
export interface HealthAlert {
  key: string;
  subject: string;
  detail: string;
}

/** Список алертов по снимку. Пустой — всё в норме. */
export function evaluateHealth(
  s: HealthSnapshot,
  t: HealthThresholds,
  nowMs: number,
): HealthAlert[] {
  const alerts: HealthAlert[] = [];

  // (1) Сверка не ЗАПУСКАЛАСЬ дольше порога — авария: планировщик не крутится
  //     или процесс мёртв. Только если сверка вообще включена (без источника
  //     снимка она не работает, и устаревание тут не сигнал).
  //
  //     ВАЖНО: считаем по попыткам, а не по успехам. Прогон, осознанно
  //     пропустивший протухшую выгрузку, — это исправная работа защиты.
  //     Про сам протухший снимок сигналит отдельный алерт ниже.
  if (s.reconcileEnabled) {
    const ageMs = s.lastReconcileAt
      ? nowMs - s.lastReconcileAt.getTime()
      : Infinity;
    if (ageMs > t.reconcileMaxAgeHours * 3_600_000) {
      alerts.push({
        key: 'reconcile_stale',
        subject: 'Ночная сверка с Эвотором не запускалась',
        detail: s.lastReconcileAt
          ? `Последний запуск: ${s.lastReconcileAt.toISOString()} (> ${t.reconcileMaxAgeHours} ч назад). Похоже, планировщик не работает — проверьте, жив ли процесс бэкенда, и логи.`
          : 'Сверка ни разу не запускалась. Проверьте настройки источника снимка и логи.',
      });
    }
  }

  // (2) Снимок остатков давно не применялся — операционный сигнал, не авария.
  //     Сверка исправно запускается, но применять нечего: выгрузку не обновляли
  //     (или она протухла и защита её отбросила). Порог задаётся ритмом
  //     обновления: при недельном ритме суточный порог кричал бы впустую.
  if (s.reconcileEnabled && t.snapshotMaxAgeHours) {
    const ageMs = s.lastSnapshotAt
      ? nowMs - s.lastSnapshotAt.getTime()
      : Infinity;
    if (ageMs > t.snapshotMaxAgeHours * 3_600_000) {
      const days = Math.round(t.snapshotMaxAgeHours / 24);
      alerts.push({
        key: 'snapshot_stale',
        subject: 'Пора обновить выгрузку остатков',
        detail: s.lastSnapshotAt
          ? `Последний применённый снимок остатков: ${s.lastSnapshotAt.toISOString()} (больше ${days} дн назад). Остатки продающихся товаров ведут чеки и остаются верными, но новые товары и цены не обновляются. Загрузите свежую выгрузку в админке.`
          : 'Снимок остатков ни разу не применялся. Загрузите выгрузку в админке.',
      });
    }
  }

  // (2) События Эвотора зависли в 'failed' — признак недоставки/непроходящей
  //     обработки вебхуков (Эвотор ретраит только до 200; см. EvotorService).
  if (s.failedEventCount > 0) {
    alerts.push({
      key: 'events_failed',
      subject: 'Не обработаны события Эвотора',
      detail: `${s.failedEventCount} событий висят в статусе «ошибка». Возможна недоставка/сбой обработки вебхуков — проверьте журнал webhook_events.`,
    });
  }

  // (3) Страховочный поллинг документов сбоит — сама страховка от недоставки
  //     вебхуков не работает (ТЗ п.9). Алертим, только если поллинг включён И
  //     реально пытался прогоняться (был токен): pollLastStatus==='error'.
  //     Отсутствие прогонов (null, нет токена) шумом в dev не считаем.
  if (s.pollEnabled && s.pollLastStatus === 'error') {
    alerts.push({
      key: 'poll_unhealthy',
      subject: 'Страховочный поллинг документов сбоит',
      detail:
        'Последний прогон поллинга Cloud API завершился ошибкой (недоступность api.evotor.ru или протухший токен). Внутрисуточная страховка от недоставки вебхуков не работает — проверьте доступ к Эвотору.',
    });
  }

  // (4) Растут unparsed-события — вероятно, Эвотор сменил формат payload:
  //     чеки перестают разбираться МОЛЧА (ни failed, ни ретраев — мы отвечаем
  //     200), остатки замирают до суточной сверки. Ровно так конверт
  //     «Чеки ver.2» однажды тихо сломал списание — это ранний сигнал.
  if ((s.unparsedRecentCount ?? 0) >= UNPARSED_ALERT_MIN) {
    alerts.push({
      key: 'unparsed_growth',
      subject: 'События Эвотора перестали разбираться',
      detail: `За последние сутки ${s.unparsedRecentCount} событий сохранены как unparsed — возможно, Эвотор изменил формат payload. Чеки могут не применяться к остаткам (двигает только суточная сверка). Проверьте payload в webhook_events (type='unparsed').`,
    });
  }

  return alerts;
}

/**
 * Гашение повторов алертов.
 *
 * Проверка здоровья идёт раз в час, поэтому проблема, которая держится
 * сутками (например, выгрузку давно не обновляли), присылала один и тот же
 * текст каждый час. Такой поток перестают читать, и настоящая авария теряется
 * среди повторов — это хуже, чем отсутствие мониторинга.
 *
 * Правило: один ключ повторяем не чаще раза в cooldownMs. Новая проблема
 * уходит немедленно. Исчезновение проблемы забывает метку, поэтому её возврат
 * тоже уведомит сразу, а не после окна молчания.
 *
 * Состояние держим в памяти процесса: после перезапуска бэкенда живая проблема
 * напомнит о себе один лишний раз — это дешевле, чем таблица в БД ради
 * подавления дублей.
 */
export function dueAlerts(
  alerts: HealthAlert[],
  sentAt: ReadonlyMap<string, number>,
  nowMs: number,
  cooldownMs: number,
): { send: HealthAlert[]; sentAt: Map<string, number> } {
  const active = new Set(alerts.map((a) => a.key));
  const next = new Map<string, number>();
  // Метки только по ЖИВЫМ проблемам: пропавшая забывается.
  for (const [key, at] of sentAt) if (active.has(key)) next.set(key, at);

  const send: HealthAlert[] = [];
  for (const a of alerts) {
    const last = next.get(a.key);
    if (last === undefined || nowMs - last >= cooldownMs) {
      send.push(a);
      next.set(a.key, nowMs);
    }
  }
  return { send, sentAt: next };
}
