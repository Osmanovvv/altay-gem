/**
 * Кому уходят уведомления бота.
 *
 * Получатели заводятся контент-менеджером в админке («Получатели уведомлений»),
 * каждый отмечает галочками, что ему интересно: заказы, технические оповещения
 * или и то и другое. Заказчице не нужен программист, чтобы добавить менеджера.
 *
 * ПРО ПЕРСОНАЛЬНЫЕ ДАННЫЕ. Разделение на два вида — не только удобство. В
 * уведомлении о заказе есть имя, телефон и адрес покупателя, и политика
 * обработки ПД называет получателями «сотрудников магазина». Подрядчику на
 * техподдержке нужны сбои сверки, а не чужие адреса, — поэтому он подписывается
 * только на оповещения, и круг тех, кто видит данные покупателей, не растёт.
 */

export type NotifyKind = 'order' | 'alert';

export interface Recipient {
  chatId: string;
  name: string;
  orders: boolean;
  alerts: boolean;
  enabled: boolean;
}

export interface FallbackChats {
  /** Чат магазина из настроек сервера — страховка, чтобы заказ не пропал. */
  adminChatId?: string;
  /** Аварийный чат для оповещений — получает их ВСЕГДА, см. ниже. */
  alertChatId?: string;
}

/**
 * Список чатов для отправки, без повторов.
 *
 * Два правила отличаются намеренно:
 *
 * ОПОВЕЩЕНИЯ — аварийный адрес из настроек добавляется ВСЕГДА, вдобавок к
 * списку. Этот канал существует, чтобы сообщить «что-то сломалось»; если его
 * получатели живут только в админке, то при падении админки или случайном
 * удалении записей не придёт именно то сообщение, которое об этом говорит, а
 * тишина неотличима от «всё хорошо».
 *
 * ЗАКАЗЫ — адрес из настроек подставляется ТОЛЬКО когда подписчиков нет вовсе.
 * Заказ обязан доехать хоть куда-то, иначе магазин его не увидит. Но как только
 * в списке появился хоть один подписчик, источник правды — список: заказчица
 * управляет им сама, и навязанный сверху адрес ей мешал бы.
 */
export function recipientsFor(
  kind: NotifyKind,
  recipients: Recipient[],
  fallback: FallbackChats,
): string[] {
  const subscribed = recipients
    .filter((r) => r.enabled && (kind === 'order' ? r.orders : r.alerts))
    .map((r) => r.chatId.trim())
    .filter(Boolean);

  const chats =
    kind === 'alert'
      ? [...subscribed, ...(fallback.alertChatId?.trim() ? [fallback.alertChatId.trim()] : [])]
      : subscribed.length > 0
        ? subscribed
        : fallback.adminChatId?.trim()
          ? [fallback.adminChatId.trim()]
          : [];

  return [...new Set(chats)];
}

/**
 * Кому отправить проверочное сообщение при обновлении списка.
 *
 * Проверочное сообщение закрывает главную беду настройки руками: неверный номер
 * чата или бот, не добавленный в группу, всплывают сразу, а не через неделю на
 * первом заказе — отсутствие уведомлений заметить трудно.
 *
 * `previous === null` означает первое чтение после запуска сервера: состав
 * запоминаем молча. Иначе каждый перезапуск рассылал бы «проверку связи» всему
 * списку заново.
 */
export function newcomers(previous: Set<string> | null, current: string[]): string[] {
  if (previous === null) return [];
  return current.filter((c) => !previous.has(c));
}
