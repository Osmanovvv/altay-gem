/**
 * Число на значке корзины в шапке.
 *
 * ПОЧЕМУ ШТУКИ, А НЕ ПОЗИЦИИ. ТЗ 6.1 просило «счётчик позиций», и так и было
 * сделано. На проверке это провалилось: шестнадцать нажатий «В корзину» по
 * одному товару оставляли на значке «1», и кнопка выглядела сломанной —
 * непонятно, добавилось или нет. Отступление от ТЗ 6.1 согласовано.
 */

interface Countable {
  quantity: number;
}

export function cartUnitCount(items: readonly Countable[]): number {
  return items.reduce((sum, i) => {
    const q = Number(i.quantity);
    // NaN и отрицательные в корзину попасть не должны, но значок в шапке —
    // не то место, где стоит падать из-за кривой записи в localStorage.
    return Number.isFinite(q) && q > 0 ? sum + q : sum;
  }, 0);
}
