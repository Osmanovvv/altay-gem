/**
 * Чипы над названием на странице товара: категория и подкатегория.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ УСЛОВИЕ В РАЗМЕТКЕ. Адаптер витрины
 * (api.ts, toProduct) подставляет вместо пустой подкатегории имя категории —
 * это нужно карточке каталога и MAX, где чип ровно один и пустым он выглядел
 * бы дырой. Страница товара рисует ДВА чипа подряд, и на товарах без
 * подкатегории выходило «ЗДОРОВЬЕ АЛТАЯ» «ЗДОРОВЬЕ АЛТАЯ». На витрине так
 * выглядели 164 карточки из 577 — все, где подкатегорию осознанно оставили
 * пустой (правило «пустое лучше неверного»).
 *
 * Фолбэк в адаптере не трогаем, а дубль срезаем здесь — там, где он видён.
 */

export function productChips(
  categoryName: string | null | undefined,
  subcategory: string | null | undefined,
): string[] {
  const category = (categoryName ?? "").trim();
  const sub = (subcategory ?? "").trim();
  const chips: string[] = [];
  if (category) chips.push(category);
  // Сравниваем без оглядки на регистр: из кассы имена приходят как попало,
  // и «ЗАМОРОЗКА» рядом с «Заморозка» — тот же самый дубль.
  if (sub && sub.toLowerCase() !== category.toLowerCase()) chips.push(sub);
  return chips;
}
