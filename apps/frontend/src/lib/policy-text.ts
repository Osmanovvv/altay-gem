/**
 * Разбор правового текста из админки на блоки для вёрстки.
 *
 * Политика хранится в Strapi одним полем обычного текста: контент-менеджер
 * правит её как в блокноте, без разметки. Раньше страница выводила это поле
 * одним куском с `white-space: pre-line` — читаемо, но заголовки разделов
 * ничем не отличались от текста, и документ выглядел сплошным полотном.
 *
 * Разметку намеренно НЕ вводим: любой её вариант (markdown, html) заказчица
 * рано или поздно сломает, и страница покажет сырые символы. Вместо этого
 * опознаём то, что и так есть в тексте, — нумерованный заголовок капсом.
 *
 * Главное свойство: текст, набранный БЕЗ этой договорённости, обязан
 * отрисоваться обычными абзацами и ничего не потерять. Поэтому распознавание
 * строгое, а всё нераспознанное — абзац.
 */

export interface PolicyBlock {
  kind: "heading" | "paragraph";
  text: string;
}

/**
 * Заголовок раздела: одиночная строка вида «7. ТРАНСГРАНИЧНАЯ ПЕРЕДАЧА».
 * Требуем номер с точкой И отсутствие строчных букв — по отдельности каждый
 * признак слишком слаб: с цифры начинаются обычные предложения, а капсом
 * бывает выделено слово внутри абзаца.
 */
const HEADING = /^\d+\.\s+[^a-zа-яё]+$/u;

export function parsePolicyText(text: string): PolicyBlock[] {
  if (!text.trim()) return [];

  return text
    .split(/\n\s*\n/)
    .map((block) => block.trim())
    .filter(Boolean)
    .map((block) => ({
      kind: !block.includes("\n") && HEADING.test(block) ? "heading" : "paragraph",
      text: block,
    }));
}
