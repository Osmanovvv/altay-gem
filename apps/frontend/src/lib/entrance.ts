/**
 * initial-проп для въездной анимации карточек.
 *
 * ЗАЧЕМ. framer-motion сериализует initial прямо в SSR-разметку, поэтому
 * сервер отдавал /catalog с двадцатью четырьмя элементами в opacity:0: все
 * двенадцать карточек первого экрана и их обёртки. Готовая страница приезжала
 * НЕВИДИМОЙ и проявлялась только после того, как догрузится и отработает
 * ~150 КБ JS — да ещё лесенкой, с задержкой до 320 мс. Смысл SSR для первого
 * экрана обнулялся, а на телефоне это читалось как «карточки дёргаются».
 *
 * Поэтому на первой отрисовке (сервер и первый клиентский рендер) анимации
 * нет — разметка видна сразу. После гидратации анимация возвращается, и смена
 * фильтра или страницы по-прежнему выглядит живой.
 */

export function entranceInitial(
  hydrated: boolean,
  offsetY: number,
): false | { opacity: number; y: number } {
  return hydrated ? { opacity: 0, y: offsetY } : false;
}
