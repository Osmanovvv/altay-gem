import { describe, expect, test } from "bun:test";
import { productChips } from "./product-chips";

describe("чипы над названием товара", () => {
  /**
   * Ради этого всё и написано. Адаптер витрины подставляет вместо пустой
   * подкатегории имя категории (чтобы карточка каталога не показывала пустой
   * чип), а страница товара рисовала оба чипа подряд — и покупатель видел
   * «ЗДОРОВЬЕ АЛТАЯ» «ЗДОРОВЬЕ АЛТАЯ». На витрине так выглядели 164 товара
   * из 577 — все, у кого подкатегория осознанно оставлена пустой.
   */
  test("не повторяет категорию, если подкатегория совпала с ней", () => {
    expect(productChips("Здоровье Алтая", "Здоровье Алтая")).toEqual(["Здоровье Алтая"]);
  });

  test("показывает обе, когда подкатегория своя", () => {
    expect(productChips("Здоровье Алтая", "Пантопродукция")).toEqual([
      "Здоровье Алтая",
      "Пантопродукция",
    ]);
  });

  test("пустая подкатегория — только категория", () => {
    expect(productChips("Сладости", null)).toEqual(["Сладости"]);
    expect(productChips("Сладости", "")).toEqual(["Сладости"]);
    expect(productChips("Сладости", "   ")).toEqual(["Сладости"]);
  });

  test("без категории не рисуем пустое место", () => {
    expect(productChips(null, null)).toEqual([]);
    expect(productChips("", "Мыло")).toEqual(["Мыло"]);
  });

  /** Из кассы имена приходят как попало — регистр и пробелы не должны плодить дубль. */
  test("совпадение ловится без оглядки на регистр и лишние пробелы", () => {
    expect(productChips("Заморозка", " заморозка ")).toEqual(["Заморозка"]);
    expect(productChips("Мёд и пчелопродукция", "МЁД И ПЧЕЛОПРОДУКЦИЯ")).toEqual([
      "Мёд и пчелопродукция",
    ]);
  });
});
